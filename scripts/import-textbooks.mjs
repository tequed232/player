/**
 * 教材库 → Android Kotlin 数据（单一数据源：web/src/data/textbooks.json）。
 *
 * Usage: node scripts/import-textbooks.mjs
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const SOURCE = 'web/src/data/textbooks.json';
const OUTPUT = 'app/src/main/java/com/app/m3expressive/TextbookData.kt';

const library = JSON.parse(await readFile(SOURCE, 'utf8'));
const kt = (value) => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const entries = library
  .map(
    (entry) => `    Textbook(
        course = ${kt(entry.course)},
        title = ${kt(entry.title)},
        publisher = ${kt(entry.publisher)},${entry.edition ? `\n        edition = ${kt(entry.edition)},` : ''}${
          entry.series ? `\n        series = ${kt(entry.series)},` : ''
        }${entry.reference ? '\n        reference = true,' : ''}
    )`,
  )
  .join(',\n');

const kotlin = `package com.app.m3expressive

/* AUTO-GENERATED by scripts/import-textbooks.mjs - do not edit by hand.
   Source: web/src/data/textbooks.json（由 12 张教材封面照片整理）*/

/** 一门课程的教材。 */
data class Textbook(
    val course: String,
    val title: String,
    val publisher: String,
    val edition: String? = null,
    val series: String? = null,
    /** 课程归属为推断匹配，界面上会标注“参考” */
    val reference: Boolean = false,
)

/** 内置教材库：课程名 → 教材。 */
object TextbookLibrary {
    val all = listOf(
${entries}
    )

    private val byCourse = all.associateBy { it.course }

    /** 课程名 → 教材（先精确匹配，再按去掉括号后的名字匹配）。 */
    fun forCourse(courseName: String): Textbook? =
        byCourse[courseName] ?: byCourse.entries.firstOrNull { (course, _) ->
            normalize(course) == normalize(courseName) ||
                normalize(course).startsWith(normalize(courseName)) ||
                normalize(courseName).startsWith(normalize(course))
        }?.value

    private fun normalize(name: String): String =
        name.replace(Regex("[（(][^）)]*[）)]"), "").replace(Regex("[\\\\s·・、,，.。:：-]"), "").lowercase()
}
`;

await mkdir(path.dirname(path.resolve(OUTPUT)), { recursive: true });
await writeFile(OUTPUT, kotlin, 'utf8');
console.log(`wrote ${OUTPUT} (${library.length} textbooks)`);
